#!/bin/sh
# Generates .env with strong random development secrets (`make dev-env`).
# Refuses to overwrite an existing .env. Never commit the result.
set -eu
cd "$(dirname "$0")/.."
rnd() { openssl rand -base64 48 | tr -d '/+=\n' | cut -c1-"${1:-32}"; }
umask 077
if [ -f .env ]; then
  # Upgrade path: add keys introduced by later stages, never overwrite existing ones.
  added=""
  for key in COURSES_DB_PASSWORD COURSES_INTERNAL_TOKEN GRADING_DB_PASSWORD ANOMALY_DB_PASSWORD; do
    if ! grep -q "^$key=" .env; then echo "$key=$(rnd 32)" >> .env; added="$added $key"; fi
  done
  echo ".env exists; added missing keys:${added:- none}"
  exit 0
fi
{
  echo "# Generated by scripts/dev-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Development only."
  echo "POSTGRES_PASSWORD=$(rnd 32)"
  echo "AUTH_DB_PASSWORD=$(rnd 32)"
  echo "COURSES_DB_PASSWORD=$(rnd 32)"
  echo "COURSES_INTERNAL_TOKEN=$(rnd 48)"
  echo "QUIZZES_DB_PASSWORD=$(rnd 32)"
  echo "GRADING_DB_PASSWORD=$(rnd 32)"
  echo "ANOMALY_DB_PASSWORD=$(rnd 32)"
  echo "REDIS_PASSWORD=$(rnd 32)"
  echo "MONGO_PASSWORD=$(rnd 32)"
  echo "MINIO_ROOT_PASSWORD=$(rnd 32)"
  echo "# Ed25519 seed (32 random bytes, base64) for access tokens."
  echo "AUTH_JWT_SIGNING_KEY=$(openssl rand -base64 32)"
  echo "AUTH_BOOTSTRAP_ADMIN_EMAIL=admin@examory.local"
  echo "AUTH_BOOTSTRAP_ADMIN_PASSWORD=$(rnd 24)"
  echo "# Research replay through the real pipeline; keep disabled unless replaying."
  echo "QUIZZES_SIM_CLOCK=disabled"
  echo "# Set by make anomaly-model (SHA-256 pin of the pickle artifact)."
  echo "ANOMALY_MODEL_SHA256="
} > .env
echo "wrote .env (mode 600). Bootstrap admin: admin@examory.local; its password is in .env"
