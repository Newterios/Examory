"""Build refs.bib for the SIST paper: the entries cited in paper.tex, copied from
../references.bib without their `note` fields (IEEEtran would print them), plus
the IEEEtran control entry that abbreviates lists of six or more authors."""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
tex = (HERE / "paper.tex").read_text(encoding="utf-8")
bib = (HERE.parent / "references.bib").read_text(encoding="utf-8")

cited: list[str] = []
for group in re.findall(r"\\cite\{([^}]*)\}", tex):
    for key in group.split(","):
        key = key.strip()
        if key and key not in cited:
            cited.append(key)

entries: dict[str, str] = {}
for match in re.finditer(r"^@\w+\{([^,]+),.*?^\}\n", bib, flags=re.S | re.M):
    entries[match.group(1)] = match.group(0)

missing = [key for key in cited if key not in entries]
if missing:
    raise SystemExit(f"cited but not in references.bib: {missing}")

out = [
    "% Generated by make_refs.py from ../references.bib; do not edit by hand.\n",
    "@IEEEtranBSTCTL{IEEEexample:BSTcontrol,\n"
    "  CTLuse_forced_etal = \"yes\",\n"
    "  CTLmax_names_forced_etal = \"5\",\n"
    "  CTLnames_show_etal = \"1\"\n}\n",
]
for key in cited:
    entry = re.sub(r",\s*\n\s*note = \{[^\n]*\}(?=\s*\n\})", "", entries[key])
    entry = re.sub(r"\n\s*note = \{[^\n]*\},?", "", entry)
    out.append(entry)
(HERE / "refs.bib").write_text("".join(out), encoding="utf-8")
print(f"{len(cited)} references written")
